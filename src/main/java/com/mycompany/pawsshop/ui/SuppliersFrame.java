    private void btn_addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_addActionPerformed
        String name = supplierName.getText();
        String email = emailTxtF.getText();
        String contact = contacttxtF.getText();

        // Validate name
        if (name.isEmpty() || !name.matches("[a-zA-Z\\s]+")) {
            JOptionPane.showMessageDialog(this, "Name should only contain letters and spaces.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate email
        if (email.isEmpty() || !email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
            JOptionPane.showMessageDialog(this, "Please enter a valid email address.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate contact number
        if (contact.isEmpty() || !contact.matches("\\d{10}")) {
            JOptionPane.showMessageDialog(this, "Contact number must be exactly 10 digits and contain only numbers.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Automatically generate the next supplier ID
        int supplierId = nextSupplierId++;

        // Add the new supplier to the list
        suppliers.add(new Supplier(supplierId, name, email, contact));

        // Add the new supplier directly to the table
        tableModel.addRow(new Object[]{supplierId, name, email, contact});

        // Save updated suppliers list to file
        DataPersistence.saveSuppliers(suppliers);

        clearFields();
        JOptionPane.showMessageDialog(this, "Supplier added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btn_addActionPerformed

    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
        int selectedRow = supplierDataT.getSelectedRow();

        if (selectedRow >= 0) {
            // Display a confirmation dialog
            int confirm = JOptionPane.showConfirmDialog(this,
                    "Are you sure you want to delete the selected supplier?",
                    "Confirm Deletion",
                    JOptionPane.YES_NO_OPTION);

            if (confirm == JOptionPane.YES_OPTION) {
                // Remove the supplier from the list
                suppliers.remove(selectedRow);

                // Remove the row from the table
                tableModel.removeRow(selectedRow);
                
                DataPersistence.saveSuppliers(suppliers);

                clearFields();
                JOptionPane.showMessageDialog(this, "Supplier deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Please select a supplier to delete.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_deleteActionPerformed

    private void btn_updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_updateActionPerformed
        int selectedRow = supplierDataT.getSelectedRow();

        if (selectedRow >= 0) {
            String name = supplierName.getText();
            String email = emailTxtF.getText();
            String contact = contacttxtF.getText();

            // Validate name
            if (name.isEmpty() || !name.matches("[a-zA-Z\\s]+")) {
                JOptionPane.showMessageDialog(this, "Name should only contain letters and spaces.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Validate email
            if (email.isEmpty() || !email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
                JOptionPane.showMessageDialog(this, "Please enter a valid email address.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Validate contact number
            if (contact.isEmpty() || !contact.matches("\\d{10}")) {
                JOptionPane.showMessageDialog(this, "Contact number must be exactly 10 digits and contain only numbers.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Update the supplier in the list
            Supplier supplier = suppliers.get(selectedRow);
            supplier.setName(name);
            supplier.setEmail(email);
            supplier.setContact(contact);

            // Update the table row
            tableModel.setValueAt(name, selectedRow, 1);
            tableModel.setValueAt(email, selectedRow, 2);
            tableModel.setValueAt(contact, selectedRow, 3);

            DataPersistence.saveSuppliers(suppliers);
            clearFields();
            JOptionPane.showMessageDialog(this, "Supplier updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Please select a supplier to update.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_updateActionPerformed

