    private void btn_downloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_downloadActionPerformed
        File file = new File("downloaded_suppliers_data.txt");

        try (BufferedWriter writer = new BufferedWriter(new FileWriter(file))) {
            writer.write("Supplier ID\tSupplier Name\tSupplier Email\tSupplier Contact");
            writer.newLine();

            for (Supplier supplier : suppliers) {
                writer.write(supplier.getSupplierId() + "\t" + supplier.getName() + "\t" + supplier.getEmail() + "\t" + supplier.getContact());
                writer.newLine();
            }

            JOptionPane.showMessageDialog(this, "Data has been saved to " + file.getAbsolutePath(), "Success", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error saving data to file: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_downloadActionPerformed

