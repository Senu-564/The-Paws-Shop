    private void btn_searchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_searchActionPerformed
        String searchQuery = searchTxt.getText();
        if (searchQuery.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a search query.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Clear the table before adding filtered data
        tableModel.setRowCount(0);

        boolean found = false;
        for (Supplier supplier : suppliers) {
            // Check if searchQuery matches ID, Name, Email, or Contact
            if (String.valueOf(supplier.getSupplierId()).equalsIgnoreCase(searchQuery)
                    || supplier.getName().equalsIgnoreCase(searchQuery)
                    || supplier.getEmail().equalsIgnoreCase(searchQuery)
                    || supplier.getContact().equalsIgnoreCase(searchQuery)) {

                // Add the matching supplier to the table
                tableModel.addRow(new Object[]{
                    supplier.getSupplierId(),
                    supplier.getName(),
                    supplier.getEmail(),
                    supplier.getContact()
                });

                found = true;
            }
        }

        if (!found) {
            JOptionPane.showMessageDialog(this, "Supplier not found.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_searchActionPerformed

