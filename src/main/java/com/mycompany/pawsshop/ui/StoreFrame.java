    private void SearchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SearchBtnActionPerformed
        String selectedCategory = (String) search_CatagorySelection.getSelectedItem();  // Get selected category

        // Clear existing rows in the table
        tableModel.setRowCount(0);

        // Iterate through the items and add those matching the selected category to the table
        for (Item item : items) {
            if (item.getCategory().equalsIgnoreCase(selectedCategory)) {  // Match category (case insensitive)
                tableModel.addRow(new Object[]{
                    item.getCategory(),
                    item.getTotalItems(),
                    item.getPrice(),
                    item.getSupplierName(),
                    item.getPayment()
                });
            }
        }

        // If no item matches the selected category, you can optionally show a message
        if (tableModel.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No items found for the selected category.", "Search Result", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_SearchBtnActionPerformed

    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
        String category = (String) search_CatagorySelection.getSelectedItem();
        String payment = txt_payment.getText();
        String price = txt_price.getText();
        String supplierName = txt_suppliername.getText();
        String totalItem = txt_totalItem.getText();

        double paymentAmount = Double.parseDouble(payment);
        double itemPrice = Double.parseDouble(price);
        int totalItems = Integer.parseInt(totalItem);

        // Create the new Item object
        Item newItem = new Item(supplierName, category, itemPrice, paymentAmount, totalItems);

        // Add the new item to the items list
        items.add(newItem);

        // Add the new item directly to the table
        DefaultTableModel model = (DefaultTableModel) storeViewTable.getModel();
        Object[] row = new Object[]{category, totalItems, itemPrice, supplierName, paymentAmount};
        model.addRow(row);

        // Save the updated items list to the file
        DataPersistence.saveItems(items);
        clearFields();

        JOptionPane.showMessageDialog(this, "Item added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_addBtnActionPerformed

    private void DeleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteBtnActionPerformed
        int selectedRow = storeViewTable.getSelectedRow();

        // Check if any row is selected
        if (selectedRow != -1) {
            // Get the supplier name (or any other unique field) of the selected item
            String supplierName = storeViewTable.getValueAt(selectedRow, 3).toString();

            // Remove the item from the items list based on the supplier name
            items.removeIf(item -> item.getSupplierName().equals(supplierName));

            // Remove the selected row from the table
            DefaultTableModel model = (DefaultTableModel) storeViewTable.getModel();
            model.removeRow(selectedRow);

            // Save the updated items list to the file
            DataPersistence.saveItems(items);

            JOptionPane.showMessageDialog(this, "Item deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Please select an item to delete.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_DeleteBtnActionPerformed

    private void UpdateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateBtnActionPerformed
        int selectedRow = storeViewTable.getSelectedRow();

        // Check if any row is selected
        if (selectedRow != -1) {
            // Get the current values of the selected item
            String currentCategory = storeViewTable.getValueAt(selectedRow, 0).toString();
            int currentTotalItems = (int) storeViewTable.getValueAt(selectedRow, 1);
            double currentItemPrice = (double) storeViewTable.getValueAt(selectedRow, 2);
            String currentSupplierName = storeViewTable.getValueAt(selectedRow, 3).toString();
            double currentPaymentAmount = (double) storeViewTable.getValueAt(selectedRow, 4);

            // Retrieve new data from the text fields
            String newCategory = (String) search_CatagorySelection.getSelectedItem();
            String newPayment = txt_payment.getText();
            String newPrice = txt_price.getText();
            String newSupplierName = txt_suppliername.getText();
            String newTotalItem = txt_totalItem.getText();

            double newPaymentAmount = Double.parseDouble(newPayment);
            double newItemPrice = Double.parseDouble(newPrice);
            int newTotalItems = Integer.parseInt(newTotalItem);

            // Find and update the item in the items list
            for (Item item : items) {
                if (item.getSupplierName().equals(currentSupplierName)) {
                    item.setCategory(newCategory);
                    item.setPrice(newItemPrice);
                    item.setPayment(newPaymentAmount);
                    item.setTotalItems(newTotalItems);

                    // Update the table row
                    DefaultTableModel model = (DefaultTableModel) storeViewTable.getModel();
                    model.setValueAt(newCategory, selectedRow, 0);
                    model.setValueAt(newTotalItems, selectedRow, 1);
                    model.setValueAt(newItemPrice, selectedRow, 2);
                    model.setValueAt(newSupplierName, selectedRow, 3);
                    model.setValueAt(newPaymentAmount, selectedRow, 4);

                    break;
                }
            }

            // Save the updated items list to the file
            DataPersistence.saveItems(items);

            clearFields();

            JOptionPane.showMessageDialog(this, "Item updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Please select an item to update.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_UpdateBtnActionPerformed

