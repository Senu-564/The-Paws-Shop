    private void btn_refreshActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_refreshActionPerformed
        // Clear existing rows in the table
        tableModel.setRowCount(0);

        // Add all items back to the table
        for (Item item : items) {
            tableModel.addRow(new Object[]{
                item.getCategory(),
                item.getTotalItems(),
                item.getPrice(),
                item.getSupplierName(),
                item.getPayment()
            });
        }
    }//GEN-LAST:event_btn_refreshActionPerformed

    private void btn_downloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_downloadActionPerformed
        File file = new File("downloaded_items_data.txt");

        try (BufferedWriter writer = new BufferedWriter(new FileWriter(file))) {
            // Write a header line (optional)
            writer.write("Item Category\tTotal Items\tItem Price\tSupplier Name\tSupplier Payment");
            writer.newLine();

            // Iterate over the items list and write each item to the file
            for (Item item : items) {
                writer.write(item.getCategory() + "\t" + item.getTotalItems() + "\t"
                        + item.getPrice() + "\t" + item.getSupplierName() + "\t"
                        + item.getPayment());
                writer.newLine();
            }

            // Inform the user that the data has been saved
            JOptionPane.showMessageDialog(this, "Data has been saved to " + file.getAbsolutePath(), "Success", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException e) {
            // Handle any errors during file writing
            JOptionPane.showMessageDialog(this, "Error saving data to file: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btn_downloadActionPerformed

